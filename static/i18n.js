const I18N_STORAGE_KEY = "lang";
let LANG = "ru";
try {
  const saved = localStorage.getItem(I18N_STORAGE_KEY);
  if (saved && I18N[saved]) LANG = saved;
} catch { /* localStorage bisa diblokir */ }

/** Terjemahan satu kunci. {var} diganti dari `vars`. */
function t(key, vars) {
  const dict = I18N[LANG] || I18N.ru;
  let text = dict[key] ?? I18N.ru[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(v);
  return text;
}

/** Pasang terjemahan ke elemen ber-atribut data-i18n* di dalam `root`. */
function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-label]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nLabel);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
}

/** Ganti bahasa: simpan pilihan, terjemahkan kerangka, lalu render ulang halaman. */
async function setLang(code) {
  if (!I18N[code]) return;
  LANG = code;
  try { localStorage.setItem(I18N_STORAGE_KEY, code); } catch { /* abaikan */ }
  document.documentElement.lang = code;
  applyStatic(document);
  markLangSwitch();
  // Halaman aktif digambar ULANG DARI DATA YANG SUDAH ADA — bukan di-fetch ulang.
  // Kalau memanggil load(), ganti bahasa ikut menunggu request jaringan
  // (halaman Toolchain Mobile bisa sampai belasan detik karena `xcrun simctl`),
  // padahal datanya tidak berubah sama sekali. Halaman yang punya `render()`
  // (pola yang sudah dipakai tabs.langs) digambar ulang seketika.
  let err = null;
  try {
    if (current && typeof current.render === "function") current.render();
    else if (current && typeof current.load === "function") await current.load();
  } catch (e) { err = e; }
  // Judul & sidebar TIDAK boleh menunggu apa pun di atas.
  if (typeof updatePageTitle === "function") updatePageTitle();
  if (typeof renderSetupBanner === "function") renderSetupBanner();
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang: code } }));
  if (err) {
    console.error("setLang: gagal menggambar ulang halaman", err);
    if (typeof toast === "function") toast(`i18n: ${err.message || err}`, true);
  }
}

function markLangSwitch() {
  document.querySelectorAll("#langSwitch [data-lang-set]").forEach((b) => {
    const on = b.dataset.langSet === LANG;
    b.classList.toggle("active", on);
    b.setAttribute("aria-checked", String(on));
  });
}

function initI18n() {
  document.documentElement.lang = LANG;
  const sw = document.getElementById("langSwitch");
  if (sw) {
    // Tombol segmen (bukan <select>) supaya sebaris dengan pemilih tema dan
    // cukup sekali klik — tanpa popup bawaan sistem.
    sw.innerHTML = I18N_LANGS.map((l) =>
      `<button role="radio" data-lang-set="${l.code}" title="${l.name}" aria-label="${l.name}">${l.short}</button>`).join("");
    sw.querySelectorAll("[data-lang-set]").forEach((b) => (b.onclick = () => setLang(b.dataset.langSet)));
    markLangSwitch();
  }
  applyStatic(document);
}
